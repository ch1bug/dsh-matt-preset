/**
 * verify-migration-review.mjs — #153 存量票据渐进复核：判据单源在场 + 必要入口 + 非空洞。
 *
 * 规约单源 = docs/agents/issue-tracker.md「存量票据渐进复核：认领前复核与现行口径回填」节
 * （判据本体）；本用例钉住它的承载脸互相可达：
 *   D1 规约节：分档表四档 / 复核三问 / 回填形态 / 样例链四步 / 反例速查五条的锚句在场。
 *   D2 分工锚：与 #148（交付责任闭环）/ #149（能力下线）的「口径时效」分工、与 #151 /
 *      Ready frontier 的边界句在场。
 *   D3 票号形态：回填评论首行模板（AI 生成标注 + <票号> 占位 + 结论三选一）在场——
 *      真票回填评论照此形态落，形态漂移即红。
 *   D4 入口链：AGENTS.md 与 batch 组件既有义务段对 docs/agents/issue-tracker.md 的指针
 *      在场（规约单源的 deliberate 指针链，非偶然存在）。
 *   D5 缺席显式声明：本票无 batch 组件常驻义务段 / brief 复核消费条——节内「显式声明缺席」
 *      句在场（缺席必须响亮，不假称已送达；加了注入面后此句改写，守卫同步改）。
 *   T1–T8 非空洞（扰动在内存副本上做，零树写入；每个扰动前自检 needle 命中 > 0）：
 *      摘整节 → D1 红；摘分档表行 → D1 红；削三问句 → D1 红；摘反例行 → D1 红；
 *      摘回填首行模板 → D3 红；摘分工段 → D2 红；摘缺席声明句 → D5 红；
 *      摘 AGENTS.md 指针 → D4 红。摘不掉守卫判据的文本手术就是假证据。
 *
 * 边界（显式声明，D16b 同族）：前提是否真被刷新、拍板记录是否真可回读，由执行会话照规约
 * 节判——本用例不写自然语言完备判定、不读线上票（gh）、不做任意旧票自动审计；它只钉
 * 判据文本在场与入口链可达。
 *
 * 纯离线：读工作树文件。无网络、无环境依赖。
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const REPO = fileURLToPath(new URL('..', import.meta.url))
const lf = (t) => String(t).replace(/\r\n/g, '\n')

const trackerText = lf(readFileSync(new URL('../docs/agents/issue-tracker.md', import.meta.url), 'utf8'))
const agentsText = lf(readFileSync(new URL('../AGENTS.md', import.meta.url), 'utf8'))
const batchComponentText = lf(readFileSync(new URL('../workflow-component-batch.txt', import.meta.url), 'utf8'))

const results = []
const ok = (name, detail = '') => results.push('  ✓ ' + name + (detail ? ' — ' + detail : ''))
const bad = (name, detail = '') => results.push('  ✗ ' + name + (detail ? ' — ' + detail : ''))

/** 命中数（needle 是字面，includes 计数）。 */
const hits = (text, needle) => text.split(needle).length - 1

/** 从文本里截取「从 startNeedle 起到 endNeedle 前」的节（找不到返回 null）。 */
const sliceBetween = (text, startNeedle, endNeedle) => {
  const start = text.indexOf(startNeedle)
  if (start === -1) return null
  const end = endNeedle == null ? text.length : text.indexOf(endNeedle, start + startNeedle.length)
  return text.slice(start, end === -1 ? text.length : end)
}

const SECTION_START = '## 存量票据渐进复核'
const SECTION_END = '\n## Ready frontier'

/** D1：规约节锚句（只在节文本内判——摘节必红，节外漂移不误伤）。 */
const sectionMissing = (text) => {
  const section = sliceBetween(text, SECTION_START, SECTION_END)
  if (section == null) return [SECTION_START + '（整节缺席）']
  const anchors = [
    // 分档表四档 + 触发点
    '| **未开工**', '| **gated**', '| **在飞**', '| **已关闭**',
    '认领 / 排批前', '阻塞边状态变化', '无复核触发点',
    // 未开工档的核心判据（句子被删或改弱必须红）
    'RFA 标签不替代当前复核', '不另建迁移标签',
    // 在飞 / 已关闭档判据
    'AC 不静默改动',
    // 复核三问
    '前提还成立吗', '待决项消了吗', '写域与边还准吗',
    // 回填形态
    '回填 = **原票评论**', 'This review note was generated by AI at',
    '前提变化 / 证据等待 / 状态更新', '不改他人票面正文', '较新的可回读',
    // 样例链（旧票进入候选 → 复核 → 原票现行口径 → 下一位执行者开工）
    '旧票进入候选', '回填评论', '下一位执行者',
    // 反例速查五条
    '旧 RFA 未复核直接开工', '正文与批准评论冲突', '在飞任务中途改 AC',
    '已关闭票仅因格式重开', '未启用团队模式却追套团队审批',
    // 边界声明
    '配方，不是自动审计',
  ]
  return anchors.filter((n) => !section.includes(n))
}

/** D2：分工锚（限节文本内——分工段被摘或改弱必须红）。 */
const divisionMissing = (text) => {
  const section = sliceBetween(text, SECTION_START, SECTION_END)
  if (section == null) return [SECTION_START + '（整节缺席）']
  const anchors = [
    '#148 需求守恒', '交付责任闭环',
    '#149 退役判据', '能力下线',
    '口径时效',
    '#151 协作契约', '实际启用',
    'Ready frontier', '不读票面文字',
  ]
  return anchors.filter((n) => !section.includes(n))
}

/** D3：回填评论票号形态（首行模板 + <票号> 占位 + 结论三选一）。 */
const headerFormMissing = (text) => {
  const section = sliceBetween(text, SECTION_START, SECTION_END)
  if (section == null) return [SECTION_START + '（整节缺席）']
  const anchors = [
    '*This review note was generated by AI at <票号> 存量复核（<批次>, <日期>）*',
    '<票号>', '<批次>', '<日期>',
    '三选一显式标注',
  ]
  return anchors.filter((n) => !section.includes(n))
}

/** D4：入口链——AGENTS.md 与 batch 组件的 issue-tracker.md 指针在场。 */
const entryChainMissing = (agents, batch) => {
  const missing = []
  if (!agents.includes('docs/agents/issue-tracker.md')) missing.push('AGENTS.md 缺 issue-tracker.md 指针')
  if (!batch.includes('docs/agents/issue-tracker.md')) missing.push('batch 组件缺 issue-tracker.md 指针')
  return missing
}

/** D5：缺席显式声明句（无常驻注入面这件事必须留在节内响亮）。 */
const absenceDeclared = (text) => {
  const section = sliceBetween(text, SECTION_START, SECTION_END)
  if (section == null) return [SECTION_START + '（整节缺席）']
  const anchors = ['显式声明缺席', 'batch 组件常驻义务段']
  return anchors.filter((n) => !section.includes(n))
}

// ---- D1 规约节 ----
{
  const missing = sectionMissing(trackerText)
  if (missing.length === 0) ok('D1 tracker: migration-review section present (tiers / three questions / backfill form / chain / counterexamples)')
  else bad('D1 tracker: migration-review section anchors missing', missing.join(' | '))
}

// ---- D2 分工锚 ----
{
  const missing = divisionMissing(trackerText)
  if (missing.length === 0) ok('D2 tracker: division anchors present (#148 delivery closure / #149 retirement / #151 collaboration / 口径时效)')
  else bad('D2 tracker: division anchors missing', missing.join(' | '))
}

// ---- D3 票号形态 ----
{
  const missing = headerFormMissing(trackerText)
  if (missing.length === 0) ok('D3 tracker: backfill-comment header form pinned (AI note + ticket placeholder + three-way verdict)')
  else bad('D3 tracker: backfill-comment header form missing / drifted', missing.join(' | '))
}

// ---- D4 入口链 ----
{
  const missing = entryChainMissing(agentsText, batchComponentText)
  if (missing.length === 0) ok('D4 entry chain: AGENTS.md + batch component both point at docs/agents/issue-tracker.md')
  else bad('D4 entry chain: pointer chain broken', missing.join(' | '))
}

// ---- D5 缺席显式声明 ----
{
  const missing = absenceDeclared(trackerText)
  if (missing.length === 0) ok('D5 tracker: absence of injected duty section explicitly declared (loud, not silent)')
  else bad('D5 tracker: absence declaration missing', missing.join(' | '))
}

// ---- T1–T8 非空洞（内存扰动，零树写入；扰动前自检 needle > 0） ----
const expectRed = (label, baseMissing, mutatedMissing) => {
  if (mutatedMissing.length > 0 && baseMissing.length === 0) ok(`T ${label}: perturbation turns the check RED (non-vacuous)`)
  else bad(`T ${label}: perturbation did NOT turn the check red`, `base=[${baseMissing}] mutated=[${mutatedMissing}]`)
}

// T1 摘整节（tracker 删「存量票据渐进复核」全节 → D1 红）
{
  const start = trackerText.indexOf(SECTION_START)
  const end = trackerText.indexOf(SECTION_END, start)
  if (start === -1 || end === -1) bad('T1 preflight: section boundary needles 0 hits')
  else {
    const mutated = trackerText.slice(0, start) + trackerText.slice(end + 1)
    expectRed('T1 whole tracker section removed', sectionMissing(trackerText), sectionMissing(mutated))
  }
}

// T2 摘分档表四行（单变量：只删四档行，不碰节外表格）
{
  const rows = ['| **未开工**', '| **gated**', '| **在飞**', '| **已关闭**']
  if (!rows.every((p) => hits(trackerText, p) >= 1)) bad('T2 preflight: tier-row needles 0 hits')
  else {
    const mutated = trackerText.split('\n').filter((l) => !rows.some((p) => l.startsWith(p))).join('\n')
    expectRed('T2 tier table rows removed', sectionMissing(trackerText), sectionMissing(mutated))
  }
}

// T3 削三问句（删「RFA 标签不替代当前复核」从句 → D1 红——判据削弱要红，不只整段摘除才红）
{
  const needle = 'RFA 标签不替代当前复核'
  if (hits(trackerText, needle) < 1) bad('T3 preflight: RFA-phrase needle 0 hits')
  else {
    const mutated = trackerText.replace(needle, 'RFA 标签即开工许可')
    expectRed('T3 RFA-phrase weakened (label-as-permission)', sectionMissing(trackerText), sectionMissing(mutated))
  }
}

// T4 摘回填首行模板（→ D3 红）
{
  const needle = '*This review note was generated by AI at <票号> 存量复核（<批次>, <日期>）*'
  if (hits(trackerText, needle) < 1) bad('T4 preflight: header-form needle 0 hits')
  else {
    const mutated = trackerText.replace(needle, '<backfill header form removed>')
    expectRed('T4 backfill header form removed', headerFormMissing(trackerText), headerFormMissing(mutated))
  }
}

// T5 摘分工段（删口径时效句 → D2 红）
{
  const needle = '本节只管存量票的**口径时效**'
  const endNeedle = '三者互不替代。'
  if (hits(trackerText, needle) < 1 || hits(trackerText, endNeedle) < 1) {
    bad('T5 preflight: division paragraph needles 0 hits — section text changed shape')
  } else {
    const start = trackerText.indexOf(needle)
    const end = trackerText.indexOf(endNeedle, start) + endNeedle.length
    const mutated = trackerText.slice(0, start) + trackerText.slice(end)
    expectRed('T5 division paragraph (口径时效) removed', divisionMissing(trackerText), divisionMissing(mutated))
  }
}

// T6 摘反例行（删「已关闭票仅因格式重开」行 → D1 红）
{
  const needle = '| 已关闭票仅因格式重开 |'
  if (hits(trackerText, needle) < 1) bad('T6 preflight: counterexample-row needle 0 hits')
  else {
    const mutated = trackerText.split('\n').filter((l) => !l.startsWith(needle)).join('\n')
    expectRed('T6 counterexample row removed', sectionMissing(trackerText), sectionMissing(mutated))
  }
}

// T7 摘缺席声明句（→ D5 红——缺席声明被删 = 假称已送达，必须红）
{
  const needle = '显式声明缺席'
  if (hits(trackerText, needle) < 1) bad('T7 preflight: absence-declaration needle 0 hits')
  else {
    const mutated = trackerText.replace('**显式声明缺席**，不假称已送达', '照常送达')
    expectRed('T7 absence declaration removed', absenceDeclared(trackerText), absenceDeclared(mutated))
  }
}

// T8 摘 AGENTS.md 指针（→ D4 红——入口链断必须红）
{
  const needle = 'docs/agents/issue-tracker.md'
  if (hits(agentsText, needle) < 1) bad('T8 preflight: AGENTS.md pointer needle 0 hits')
  else {
    // 指针在 AGENTS.md 出现多次——replace 只摘第一处会假绿（首跑实测），必须全量摘除
    const mutated = agentsText.split(needle).join('docs/agents/REDACTED.md')
    expectRed('T8 AGENTS.md pointer removed', entryChainMissing(agentsText, batchComponentText),
      entryChainMissing(mutated, batchComponentText))
  }
}

// ---- 汇总（本仓 tests/*.mjs 既有形态：results 逐行 + 非零退出） ----
console.log('=== verify-migration-review === (#153 存量票据渐进复核：认领前复核与现行口径回填)')
for (const line of results) console.log(line)
const failed = results.filter((r) => r.startsWith('  ✗')).length
if (failed > 0) {
  console.error(`\nFAILED: ${failed} 项红`)
  process.exit(1)
}
console.log('\nOK: 规约节在场（分档 / 三问 / 回填形态 / 样例链 / 反例）+ 分工锚 + 票号形态 + 入口链 + 缺席显式声明 + 扰动全红')
